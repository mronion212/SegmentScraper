// Bundle the existing userscript validators for Node without duplicating their logic.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const modules = ['state', 'output-policy', 'network', 'tvdb', 'tmdb', 'update-check'];
let output = '// Generated by build/desktop-core.cjs. Edit src/core instead.\nexport function createCore({ request, storage = new Map() }) {\nconst GM_xmlhttpRequest = request;\nconst GM_getValue = (key, fallback) => storage.has(key) ? storage.get(key) : fallback;\nconst GM_setValue = (key, value) => storage.set(key, value);\n';
for (const name of modules) {
 const source = fs.readFileSync(path.join(root, 'src/core', name + '.js'), 'utf8');
 const names = [...source.matchAll(/export (?:async )?(?:function|const|let) (\w+)/g)].map(m => m[1]);
 output += `const ${name.replaceAll('-', '_')} = (() => {\n${source.replace(/^import .*;\r?\n/gm, '').replace(/export (?=(?:async )?(?:function|const|let))/g, '')}\nreturn { ${names.join(', ')} };\n})();\n`;
 if (name === 'state') output += 'const { state, createMediaCacheKey } = stateModule;\n';
 if (name === 'output-policy') output += 'const { outputSegmentAllowed, introdbPayload } = output_policy;\n';
}
// Other modules expect the imported state object, not the module namespace.
output = output.replace('const state = (() =>', 'const stateModule = (() =>');
output += 'return { ...output_policy, ...network, ...tvdb, ...tmdb, ...update_check };\n}\n';
output=output.replace(/\r\n?/g,'\n');
if(process.argv.includes('--check')) {
 if(fs.readFileSync(path.join(root,'app/shared-core.mjs'),'utf8').replace(/\r\n?/g,'\n')!==output)throw new Error('Desktop core is stale. Run node build/desktop-core.cjs.');
}else fs.writeFileSync(path.join(root, 'app/shared-core.mjs'), output);
